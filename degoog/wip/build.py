# Builds the two files the installer embeds:
#   files/ct-page.js (installed as script.js) = core.js + answers.js (wrapped, exports kept as CT.*) + files/page/NN-*.js
#   files/index.js (the server plugin)       = files/server/NN-*.js
# The modules are concatenated in NN order into one scope (no imports between them): the page script is inlined into
# layout.html as one module, and the server file is one plugin file. Edit the modules, never the two outputs.
import re, os, glob
def cat(d): return ''.join(open(f, encoding='utf-8').read() for f in sorted(glob.glob(f'files/{d}/[0-9][0-9]-*.js')))
VERSION = os.environ.get('CT_VERSION', 'v50-preview')
# answers.js (local answer card) shares core's scope: both become CT.*
core = open('files/core.js', encoding='utf-8').read() + '\n' + open('files/answers.js', encoding='utf-8').read()
names = re.findall(r'^export const (\w+)', core, re.M)
body = re.sub(r'^export const ', 'const ', core, flags=re.M)
page = cat('page')
out = f'// clean-titles {VERSION}\n' + f'const CT_VER = "{VERSION}";\n' + 'const CT = (() => {\n' + body + '\nreturn { ' + ', '.join(names) + ' };\n})();\n' + page
open('files/ct-page.js', 'w', encoding='utf-8').write(out)
print('ct-page.js', len(out), 'chars;', len(names), 'core exports')
# files/fixed.json: {report id: version} for the reports releases fixed (written by the Report session), built in as
# CT_FIXED so the installed version can tell you once that your report's fix is in
import json
fixed = json.load(open('files/fixed.json', encoding='utf-8')) if os.path.exists('files/fixed.json') else {}
server = ('// clean-titles server plugin: GENERATED by build.py from files/server/NN-*.js (edit those, not this file)\n'
          + f'const CT_FIXED = {json.dumps(fixed, sort_keys=True)};\n' + cat('server'))
open('files/index.js', 'w', encoding='utf-8').write(server)
print('index.js', len(server), 'chars')

# MAP.md: every feature (the "// =====" sections), function and server route with its file:line, so a chat reads
# only the lines it needs. Rewritten on every build; QUICKSTART links it.
def build_map():
    out = ['# clean-titles map (generated by build.py: do not edit)', '',
           'Every section, function and route in degoog/wip/files with its line. Read the lines you need (`sed -n A,Bp file`), not whole files.',
           'Server = files/server/NN-*.js (built into files/index.js), page = files/page/NN-*.js (built into files/ct-page.js after core.js + answers.js): edit the modules.', '']
    mods = sorted(glob.glob('files/server/[0-9][0-9]-*.js')) + sorted(glob.glob('files/page/[0-9][0-9]-*.js'))
    srcs = [m[len('files/'):] for m in mods] + ['core.js', 'answers.js', 'ctcheck.js', 'names.js', 'inline.js', 'safeoff.js', 'aittl.js', 'setcss.js']
    fn = re.compile(r'^(?:export )?(?:const|let|function|async function) ([A-Za-z_$][\w$]*)\s*(?:=\s*(?:async\s*)?(?:\(|[A-Za-z_$][\w$]*\s*=>|function)|\()')
    for f in srcs:
        p = f'files/{f}'
        if not os.path.exists(p): continue
        lines = open(p, encoding='utf-8').read().split('\n')
        out.append(f'## {f} ({len(lines)} lines)')
        route_path = None
        for i, l in enumerate(lines, 1):
            m = re.match(r'^// =====\s*(.+?)\s*=====', l)
            if m: out.append(f'- **{m.group(1)}** :{i}'); continue
            m = fn.match(l)
            if m: out.append(f'  - `{m.group(1)}` :{i}'); continue
            m = re.match(r'^\s+path: "(/[\w-]+)"', l)
            if m and f.startswith('server/'): out.append(f'  - route `{m.group(1)}` :{i}')
            m = re.match(r'^globalThis\.(\w+) =', l)
            if m: out.append(f'  - `globalThis.{m.group(1)}` :{i}')
        out.append('')
    css = open('files/custom.css', encoding='utf-8').read().split('\n')
    out.append(f'## custom.css ({len(css)} lines)')
    for i, l in enumerate(css, 1):
        m = re.match(r'^/\*\s*([^*]{3,90}?)(?::|\*/|\.|$)', l)
        if m: out.append(f'- {m.group(1).strip()} :{i}')
    # vision/app.py (ct-vision on the PC's GPU): functions and routes
    vp = 'files/vision/app.py'
    if os.path.exists(vp):
        vl = open(vp, encoding='utf-8').read().split('\n')
        out += ['', f'## vision/app.py ({len(vl)} lines)']
        for i, l in enumerate(vl, 1):
            m = re.match(r'^@app\.(get|post)\("(/[\w-]*)"', l)
            if m: out.append(f'  - route {m.group(1).upper()} `{m.group(2)}` :{i}'); continue
            m = re.match(r'^(?:async )?def (\w+)', l)
            if m: out.append(f'  - `{m.group(1)}` :{i}')
    out += ['', '## other', '- ../autoupdate-job.ps1: the PC\'s update job: every minute, installs a new main within ~1 min, sends reports (Issue() puts update problems on the server for ⚑ Report)',
            '- ../install.ps1: generated by patch_installer.py; never read whole, grep it', '- test/*.test.js: bun tests (they load the BUILT ct-page.js / index.js); test/render.js: degoog\'s result template for tests',
            '- test/headless/run.cjs: headless Chrome check (layout shift, pass ms, endless-scroll page 2: page2/lost/ahead); stub page without rec/', '']
    open('MAP.md', 'w', encoding='utf-8').write('\n'.join(out))
    print('MAP.md', len(out), 'lines')
build_map()
